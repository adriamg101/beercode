package Mips;

import ThreeAddressCode.Triplet;

import java.io.BufferedWriter;
import java.io.FileWriter;
import java.io.IOException;
import java.time.LocalDate;
import java.util.*;

public class Mips {
    private final List<Triplet> instructions;
    private final MMU mmu;
    private final StringBuilder dataSection = new StringBuilder("# Variable declaration\n.data\n");
    private final StringBuilder textSection = new StringBuilder(".text\n.globl main\n\n");
    private final Set<String> generatedLabels = new HashSet<>();

    private int nArguments = 0;
    private boolean isMain = false;
    private boolean isActualOR = false;
    private int actualConditional = 0;
    private int actualConditionalReg = 1;
    private int literalRegisters = 29;
    private final Stack<String> labelStack = new Stack<>();
    private final Stack<String> conditionalLabelStack = new Stack<>();
    private String lastEndIfLabel = null;
    private int currentScope = 0;

    private static final int FIRST_TMP_REG = 29;
    private static final int LAST_TMP_REG = 31;

    private static final String START_FUNCTION = "start";
    private static final String END_FUNCTION = "END FUNC";
    private static final String END_IF = "END IF";
    private static final String END_ELSE = "END ELSE";
    private static final String ELSE_GOTO = "else-goto";
    private static final String IF_GOTO = "if-goto";
    private static final String LOOP_GOTO = "goto-loop";
    private static final String EQUAL = "=";
    private static final String EQUAL_COND = "==";
    private static final String NOT_EQUAL = "!=";
    private static final String GREATER = ">";
    private static final String LOWER = "<";
    private static final String GOTO = "goto";
    private static final String RETURN = "return";
    private static final String RETURNED = "returned";
    private static final String MAIN = "main";
    private static final String ADD = "ADD";
    private static final String SUBTRACT = "SUBTRACT";
    private static final String MULTIPLY = "MULTIPLY";
    private static final String DIVIDE = "DIVIDE";
    private static final String LABEL = "Label";

    private static final Set<String> OPERATORS = new HashSet<>(Set.of("ADD", "SUBTRACT", "MULTIPLY", "DIVIDE"));
    private static final Set<String> LOGICAL_OPERATORS = new HashSet<>(Set.of("!=", "==", ">", "<"));
    private static final Set<String> LOGICAL_CONCATENATION_OPERATORS = new HashSet<>(Set.of("AND", "OR"));
    private static final String ARGS_REGEX = "args\\d+";
    private static final String LOOP_LABEL = "LL\\d+";
    private static final String ID_REGEX = "^[a-zA-Z]+\\d+(\\+\\d+)?$";



    // MIPS instructions
    private static final String REG_PROMPT = "$";
    private static final String STORE = "sw";
    private static final String LOAD_WORK = "lw";
    private static final String LOAD = "li";
    private static final String MTC1 = "mtc1";
    private static final String MFC1 = "mfc1";
    private static final String JUMP = "jal";
    private static final String JUMP_LABEL = "j";
    private static final String JUMP_RETURN = "jr";
    private static final String RETURN_ADDRESS = "$ra";
    private static final String RETURN_REGISTER = "$v0";
    private static final String ARGUMENT_REGISTER = "$a";
    private static final String ADD_INSTRUCTION = "add.s ";
    private static final String SUBTRACT_INSTRUCTION = "sub.s ";
    private static final String MULTIPLY_INSTRUCTION = "mul.s ";
    private static final String DIVIDE_INSTRUCTION = "div.s ";
    private static final String MOVE = "move ";
    private static final String RETURN0 = "\tli $v0, 10\n\tsyscall\n";
    private static final String ZERO_REG = "$zero";
    private static final String TEMP_REG = "$f";
    private static final String AUX_REG = "$t0";
    private static final String AUX_COND_REG = "$t";
    private static final String EQUAL_COMPARATOR_INS = "c.eq.s";
    private static final String NOT_EQUAL_COMPARATOR_INS = "c.eq.s";
    private static final String GREATER_COMPARATOR_INS = "c.lt.s ";
    private static final String LOWER_COMPARATOR_INS = "c.lt.s ";
    private static final String BRANCH_COMPARE_FALSE = "bc1f";
    private static final String BRANCH_COMPARE_TRUE = "bc1t";

    public Mips(List<Triplet> instructions, MMU mmu, int WORD_SIZE) {
        this.instructions = instructions;
        this.mmu = mmu;
    }

    public void generateMips(String outputFile) {
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(outputFile))) {
            writer.write("# Code generated by: BEERCODE🍺\n");
            writer.write("# Date: " + LocalDate.now() + "\n\n");

            for (int i = 0; i < this.instructions.size(); i++) {
                //System.out.println("(" + i + ") " + instructions.get(i));
                convertToMips(instructions, i);
            }

            // Write the data and text sections to the file
            writer.write(dataSection.toString());
            writer.write("\n");
            writer.write(textSection.toString());

        } catch (IOException e) {
            e.printStackTrace();
        }
    }

    private String getCondTempReg() {
        int value = this.actualConditionalReg;
        this.actualConditionalReg = (this.actualConditionalReg % 8) + 1;
        return AUX_COND_REG + value;
    }

    private String getPreviousCondTmpReg(int offset) {
        int rangeSize = 8;
        int index = ((this.actualConditionalReg - 1 - offset + rangeSize) % rangeSize) + 1;
        return AUX_COND_REG + index;
    }

    private String getLiteralRegister() {
        String reg = TEMP_REG + literalRegisters;
        literalRegisters++;
        if (literalRegisters > LAST_TMP_REG) {
            literalRegisters = FIRST_TMP_REG;
        }
        return reg;
    }

    private String getPreviousLiteralRegister(int offset) {
        int rangeSize = LAST_TMP_REG - FIRST_TMP_REG + 1;
        int index = ((literalRegisters - offset - FIRST_TMP_REG + rangeSize) % rangeSize) + FIRST_TMP_REG;
        return TEMP_REG + index;
    }


    private String makeArithmeticalOperation(String regOperand1, String regOperand2, String operator) {
        String reg_result = getLiteralRegister();
        String instruction = "\n\t# Arithmetical operations\n\t";
        switch (operator) {
            case ADD:
                instruction += ADD_INSTRUCTION;
                break;

            case SUBTRACT:
                instruction += SUBTRACT_INSTRUCTION;
                break;

            case MULTIPLY:
                instruction += MULTIPLY_INSTRUCTION;
                break;

            case DIVIDE:
                instruction += DIVIDE_INSTRUCTION;
                break;
            default:
                throw new IllegalArgumentException("Operador no soportado: " + operator);
        }
        instruction += reg_result + ", " + regOperand1 + ", " + regOperand2 + "\n\n";
        this.textSection.append(instruction);

        return reg_result;
    }


    private String getTempRegister(String operand, int index) {
        if (operand != null && operand.matches(ID_REGEX)) {
            List<String> temporari = mmu.getVar(operand, index);
            if (temporari.size() > 1) {
                for (int i = 0; i < temporari.size() - 1; i++) {
                    textSection.append("\t").append(temporari.get(i)).append("\n");
                }
            }
            return temporari.get(temporari.size() - 1);
        }
        String reg;
        if (operand.startsWith("(")) {
            reg = getPreviousLiteralRegister(1);
        } else {
            reg = getLiteralRegister();


            String loadComment = "\t# Load constant (IEEE format to reg)\n";
            this.textSection.append(loadComment);
            this.textSection.append("\t").append(LOAD).append(" ").append(AUX_REG).append(", ").append(getAscii(operand)).append("\n");
            this.textSection.append("\t").append(MTC1).append(" ").append(AUX_REG).append(", ").append(reg).append("\n");
        }
        return reg;
    }

    private String getAscii(String operand) {
        String valueToLoad;
        try {
            float operandInt = Float.parseFloat(operand);
            int bits = Float.floatToIntBits(operandInt);

            valueToLoad = String.valueOf(bits);
        } catch (NumberFormatException e) {
            if (operand.length() > 0) {
                int ascii = (int) operand.charAt(0);
                int bits = Float.floatToIntBits(ascii);
                valueToLoad = String.valueOf(bits);
            } else {
                valueToLoad = "0";
            }
        }

        return valueToLoad;
    }


    private String loadWorkToReg(Triplet instruction, int index) {
        if (instruction == null) return "";

        String operand1 = instruction.getOperand1();
        String regOperand1;
        if (operand1 != null && (operand1.matches(ID_REGEX) || operand1.startsWith("("))) {
            regOperand1 = getTempRegister(operand1, index);
        } else {
            regOperand1 = getAscii(operand1);
        }

        String operand2 = instruction.getOperand2();
        String regOperand2;
        if (operand2 != null && (operand2.matches(ID_REGEX) || operand2.startsWith("("))) {
            regOperand2 = getTempRegister(operand2, index);
        } else {
            regOperand2 = getAscii(operand2);
        }

        if (regOperand1 != null && regOperand1.startsWith("$")) {
            String tmpReg = getPreviousLiteralRegister(1);
            String tmp = getLiteralRegister();
            int regNumber = Integer.parseInt(regOperand1.substring(2));
            if (regNumber < FIRST_TMP_REG) {
                tmpReg = regOperand1;
            }
            String moveReg = "\n\t# Moving reg to reg $fX = $fY\n";
            this.textSection.append(moveReg);
            textSection.append("\t").append(MTC1).append(" ").append(ZERO_REG).append(", ").append(tmp).append("\n");
            textSection.append("\t").append(ADD_INSTRUCTION).append(regOperand2).append(", ").append(tmpReg).append(", ").append(tmp).append("\n\n");
        } else {
            String moveReg = "\n\t# Load constant (IEEE format ot reg)\n";
            this.textSection.append(moveReg);
            textSection.append("\t").append(LOAD).append(" ").append(AUX_REG).append(", ").append(regOperand1).append("\n");
            textSection.append("\t").append(MTC1).append(" ").append(AUX_REG).append(", ").append(regOperand2).append("\n\n");
        }
        return "";
    }


    private void returnFunction() {
        if (this.isMain) {
            String returnInstruction = "\t#Representative to RETURN0\n";
            this.textSection.append(returnInstruction);
            textSection.append(RETURN0);
        } else {

            String returnInstruction = "\t" + JUMP_RETURN + " " + RETURN_ADDRESS + "\n";
            textSection.append(returnInstruction);
        }
        this.nArguments = 0;
        this.isMain = false;
    }

    private void knowLogicalOperator(Triplet instruction) {
        int index = instructions.indexOf(instruction);
        Triplet condIns = instructions.get(index + 2);
        if (condIns.getOperator().equals("OR")) {
            this.isActualOR = true;
            return;
        }
        this.isActualOR = false;
    }

    private void generateConditionalJump(Triplet instruction, int index) {
        Triplet conditionalInstruction = instructions.get(instructions.indexOf(instruction) + 1);
        if (conditionalInstruction.getOperand2() != null && conditionalInstruction.getOperand2().matches(LOOP_LABEL)) {
            String loopLabelInstruction = "L" + (index + 1) + ":\n";
            this.textSection.append(loopLabelInstruction);
        }

        String operand1 = instruction.getOperand1();
        String operand2 = instruction.getOperand2();

        if (operand1 != null && operand1.startsWith("(")) {
            operand1 = getTempRegister(instruction.getOperand1(), instructions.indexOf(instruction));
            this.textSection.append("\t").append(LOAD).append(" ").append(operand1).append(", ").append(instruction.getOperand1()).append("\n");
        } else {
            operand1 = getTempRegister(instruction.getOperand1(), instructions.indexOf(instruction));
        }

        if (operand2 != null && operand2.startsWith("(")) {
            operand2 = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
            this.textSection.append("\t").append(LOAD).append(" ").append(operand2).append(", ").append(instruction.getOperand2()).append("\n");
        } else {
            operand2 = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
        }

        if (!this.conditionalLabelStack.isEmpty()) {
            String label = this.conditionalLabelStack.peek();
            this.labelStack.add(label);
        }

        String condInstruction = "\n\t";

        knowLogicalOperator(instruction);
        String condTempReg = getCondTempReg();

        switch (instruction.getOperator()) {
            case NOT_EQUAL:
                condInstruction += "# Comparing if regs are not equal\n\t";
                condInstruction += NOT_EQUAL_COMPARATOR_INS + " " + operand1 + ", " + operand2 + "\n";
                condInstruction += "\t" + BRANCH_COMPARE_FALSE + " SET_TRUE" + this.actualConditional;
                condInstruction += "\t# Jump to the label if condition is true\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 0\n";
                condInstruction += "\t" + JUMP_LABEL + " CONTINUE" + this.actualConditional + "\n";
                condInstruction += "SET_TRUE" + this.actualConditional + ":\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 1\n";
                condInstruction += "CONTINUE" + this.actualConditional + ":\n";
                break;
            case EQUAL_COND:
                condInstruction += "# Comparing if regs are equal\n\t";
                condInstruction += EQUAL_COMPARATOR_INS + " " + operand1 + ", " + operand2 + "\n";
                condInstruction += "\t" + BRANCH_COMPARE_FALSE + " SET_FALSE" + this.actualConditional;
                condInstruction += "\t# Jump to the label if condition is false\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 1\n";
                condInstruction += "\t" + JUMP_LABEL + " CONTINUE" + this.actualConditional + "\n";
                condInstruction += "SET_FALSE" + this.actualConditional + ":\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 0\n";
                condInstruction += "CONTINUE" + this.actualConditional + ":\n";
                break;
            case GREATER:
                condInstruction += "# Comparing if first reg greater than second reg\n\t";
                condInstruction += GREATER_COMPARATOR_INS + " " + operand1 + ", " + operand2 + "\n";
                condInstruction += "\t" + BRANCH_COMPARE_FALSE + " SET_FALSE" + this.actualConditional;
                condInstruction += "\t# Jump to the label if condition is false\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 1\n";
                condInstruction += "\t" + JUMP_LABEL + " CONTINUE" + this.actualConditional + "\n";
                condInstruction += "SET_FALSE" + this.actualConditional + ":\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 0\n";
                condInstruction += "CONTINUE" + this.actualConditional + ":\n";
                break;
            case LOWER:
                condInstruction += "# Comparing if first reg lower than second reg\n\t";
                condInstruction += LOWER_COMPARATOR_INS + " " + operand1 + ", " + operand2 + "\n";
                condInstruction += "\t" + BRANCH_COMPARE_FALSE + " SET_FALSE" + this.actualConditional;
                condInstruction += "\t# Jump to the label if condition is false\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 1\n";
                condInstruction += "\t" + JUMP_LABEL + " CONTINUE" + this.actualConditional + "\n";
                condInstruction += "SET_FALSE" + this.actualConditional + ":\n";
                condInstruction += "\t" + LOAD + " " + condTempReg + ", 0\n";
                condInstruction += "CONTINUE" + this.actualConditional + ":\n";
                break;

            default:
                throw new UnsupportedOperationException("Operador no soportado: " + instruction.getOperator());
        }

        this.actualConditional++;
        this.textSection.append(condInstruction);
    }

    private void handleStartFunction(Triplet instruction) {
        textSection.append("\n").append(instruction.getOperator()).append(":\n");

        if (MAIN.equals(instruction.getOperator())) {
            this.isMain = true;
        }
        this.nArguments = 0;
        this.currentScope++;
    }

    private void handleArgument(Triplet instruction) {
        String reg = getTempRegister(instruction.getOperand1(), instructions.indexOf(instruction));
        String putRegComment = "\t# Put parameter to the argument register\n";
        String argInstruction = "\t" + MFC1 + " " + ARGUMENT_REGISTER + this.nArguments + ", " + reg + "\n";
        this.textSection.append(putRegComment);
        textSection.append(argInstruction);
        this.nArguments++;
    }

    private void handleArgumentFunction(Triplet instruction) {
        String reg = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
        String getArgComment = "\t# Get the argument from the argument register\n";
        this.textSection.append(getArgComment);
        String argInstruction = "\t" + MTC1 + " " + ARGUMENT_REGISTER + this.nArguments + ", " + reg + "\n\n";
        textSection.append(argInstruction);
        this.nArguments++;
    }

    private void handleEqual(Triplet instruction) {
        loadWorkToReg(instruction, instructions.indexOf(instruction));
    }

    private void handleArithmetic(Triplet instruction) {
        String regOperand1 = getTempRegister(instruction.getOperand1(), instructions.indexOf(instruction));
        String regOperand2 = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
        makeArithmeticalOperation(regOperand1, regOperand2, instruction.getOperator());
    }

    private void handleGoto(Triplet instruction) {
        List<String> saveContextInstructions = mmu.saveContext(this.currentScope);
        this.textSection.append("\n\t#Saving context of the current scope\n");
        for (String ins : saveContextInstructions) {
            this.textSection.append("\t").append(ins).append("\n");
        }

        this.textSection.append("\n\t#Call to the function\n");
        textSection.append("\t").append(JUMP).append(" ").append(instruction.getOperand2()).append("\n");

        this.textSection.append("\n\t#Restoring context of the current scope\n");
        List<String> getContextInstructions = mmu.getContext();
        for (String ins : getContextInstructions) {
            this.textSection.append("\t").append(ins).append("\n");
        }
        this.textSection.append("\n");
    }

    private void handleReturn(Triplet instruction) {
        String reg = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
        String putToReturnRegComment = "\n\t# Put the return value to the return register\n";
        this.textSection.append(putToReturnRegComment);
        textSection.append("\t").append(MFC1 + " ").append(RETURN_REGISTER).append(", ").append(reg).append("\n");
        this.nArguments = 0;
        returnFunction();
    }

    private void handleReturned(Triplet instruction) {
        String regVar = getTempRegister(instruction.getOperand2(), instructions.indexOf(instruction));
        String getToReturnRegComment = "\t# Get the returned value from the return register\n";
        this.textSection.append(getToReturnRegComment);
        textSection.append("\t").append(MTC1).append(" ").append(RETURN_REGISTER).append(", ").append(regVar).append("\n");
        this.nArguments = 0;
    }

    private void handleEndIf(List<Triplet> instructions, int index) {
        String label;

        if (index + 1 < instructions.size()) {
            Triplet next = instructions.get(index + 1);
            if (ELSE_GOTO.equals(next.getOperator())) {
                if (!labelStack.isEmpty()) {
                    this.lastEndIfLabel = labelStack.pop();
                }

                return;
            }
        }

        if (!labelStack.isEmpty()) {
            label = this.labelStack.pop();
            if (generatedLabels.add(label)) {
                textSection.append(label).append(":\n");
            }
        }
        if (!this.conditionalLabelStack.isEmpty()) {
            this.conditionalLabelStack.pop();
        }
    }

    private void handleEndElse() {
        if (!labelStack.isEmpty()) {
            String label = labelStack.pop();
            if (generatedLabels.add(label)) {
                textSection.append(label).append(":\n");
            }
        }
        if (!this.conditionalLabelStack.isEmpty()) {
            this.conditionalLabelStack.pop();
        }
    }

    private void handleElseGoto(Triplet instruction) {
        String label = instruction.getOperand2();

        textSection.append("\t").append(JUMP_LABEL).append(" ").append(label).append("\n");

        if (lastEndIfLabel != null) {
            textSection.append(lastEndIfLabel).append(":\n");
            lastEndIfLabel = null;
        }

        labelStack.push(label);
    }

    private void handleConcatenationOperators(Triplet instruction) {
        String logicOperator = instruction.getOperator().toLowerCase();
        String regResult = getCondTempReg();
        String firsPreviousReg = getPreviousCondTmpReg(2);
        String secondPreviousRg = getPreviousCondTmpReg(3);
        String logicOperationInstruction = "\t" + logicOperator + " " + regResult + ", " + firsPreviousReg + ", " + secondPreviousRg + "\n";
        this.textSection.append(logicOperationInstruction);
    }

    private void handleIfGoTo(Triplet instruction) {
        String prevCondReg = getPreviousCondTmpReg(1);
        String jumpComment = "\n\t# Jump to the label if condition is false\n";
        if (!this.conditionalLabelStack.isEmpty()) {
            String checkCond = "\tbeq " + prevCondReg + ", " + ZERO_REG + ", " + this.conditionalLabelStack.peek() + "\n";
            this.textSection.append(jumpComment);
            this.textSection.append(checkCond);
        }
    }

    private void convertToMips(List<Triplet> instructions, int index) {
        Triplet instruction = instructions.get(index);
        String operator = instruction.getOperator();

        if (START_FUNCTION.equals(instruction.getOperand2())) {
            this.handleStartFunction(instruction);
        } else if (instruction.getOperand2() != null && instruction.getOperand2().matches(ARGS_REGEX)) {
            this.handleArgument(instruction);
        } else if (instruction.getOperand1() != null && instruction.getOperand1().matches(ARGS_REGEX)) {
            this.handleArgumentFunction(instruction);
        } else if (EQUAL.equals(operator)) {
            this.handleEqual(instruction);
        } else if (OPERATORS.contains(operator)) {
            this.handleArithmetic(instruction);
        } else if (LOGICAL_CONCATENATION_OPERATORS.contains(operator)) {
            this.handleConcatenationOperators(instruction);
        } else if (GOTO.equals(operator)) {
            this.handleGoto(instruction);
        } else if (END_FUNCTION.equals(operator)) {
            this.returnFunction();
        } else if (RETURN.equals(operator)) {
            this.handleReturn(instruction);
        } else if (RETURNED.equals(operator)) {
            this.handleReturned(instruction);
        } else if (LOGICAL_OPERATORS.contains(operator)) {
            this.generateConditionalJump(instruction, index);
        } else if (END_IF.equals(operator)) {
            this.handleEndIf(instructions, index);
        } else if (ELSE_GOTO.equals(operator)) {
            this.handleElseGoto(instruction);
        } else if (END_ELSE.equals(operator)) {
            this.handleEndElse();
        } else if (LOOP_GOTO.equals(operator)) {
            String gotoInstruct = "\t" + JUMP_LABEL + " " + instruction.getOperand2() + "\n";
            this.textSection.append(gotoInstruct);
            if (!this.conditionalLabelStack.isEmpty()) {
                String label = this.labelStack.pop() + ":\n";
                this.textSection.append(label);
            }
        } else if (LABEL.equals(operator)) {
            this.conditionalLabelStack.add(instruction.getOperand2());
            String labelInstruction = "L" + instructions.indexOf(instruction) + ":\n";
            this.textSection.append(labelInstruction);
        } else if (IF_GOTO.equals(operator)) {
            this.handleIfGoTo(instruction);
        }
    }

}
